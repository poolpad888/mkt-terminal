'use strict';
// ── Аукционы ОФЗ: чтение сайта Минфина ───────────────────────────────────
// Раздел «Аукционы» держит четыре ленты, у каждой свой номер в адресе:
//   id_65 — таблицы планируемых аукционов (график на квартал),
//   id_38 — сообщения о проведении (выходят во вторник, про завтрашний день),
//   id_39 — результаты размещения по каждому выпуску (среда, после торгов),
//   id_66 — сводные таблицы по результатам.
// Нам нужны вторая и третья. Разбор держим отдельно от сервера, чтобы его
// можно было проверить на сохранённой странице, не выходя в сеть.

const РАЗДЕЛ = 'https://minfin.gov.ru/ru/perfomance/public_debt/internal/operations/ofz/auction';
const БАЗА = 'https://minfin.gov.ru';

const МЕСЯЦЫ = { 'января':1,'февраля':2,'марта':3,'апреля':4,'мая':5,'июня':6,
                 'июля':7,'августа':8,'сентября':9,'октября':10,'ноября':11,'декабря':12 };

function текст(html) {
  let t = String(html || '');
  t = t.replace(/<script[\s\S]*?<\/script>/gi, ' ').replace(/<style[\s\S]*?<\/style>/gi, ' ');
  t = t.replace(/<[^>]+>/g, ' ').replace(/&nbsp;/g, ' ').replace(/&laquo;|&raquo;/g, '"')
       .replace(/&[a-z]+;/gi, ' ');
  return t.replace(/\s+/g, ' ').trim();
}

// «9 сентября 2026 года» → 2026-09-09
function датаИзТекста(с) {
  const m = /(\d{1,2})\s+([а-яё]+)\s+(\d{4})/i.exec(с || '');
  if (!m) return '';
  const мес = МЕСЯЦЫ[m[2].toLowerCase()];
  if (!мес) return '';
  return m[3] + '-' + String(мес).padStart(2, '0') + '-' + String(+m[1]).padStart(2, '0');
}

// Ссылки нужной ленты вместе с заголовками. Заголовок берём из текста ссылки:
// в списке он совпадает с названием документа.
function ссылкиЛенты(html, лента) {
  const out = [];
  const re = new RegExp('<a[^>]+href="([^"]*\\bid_' + лента + '=(\\d+)-[^"]*)"[^>]*>([\\s\\S]{0,400}?)<\\/a>', 'gi');
  let m;
  while ((m = re.exec(html))) {
    const адрес = m[1].startsWith('http') ? m[1] : БАЗА + m[1];
    const назв = текст(m[3]);
    if (!назв) continue;
    if (out.some(x => x.id === m[2])) continue;
    out.push({ id: m[2], url: адрес.replace(/&amp;/g, '&'), title: назв });
  }
  return out;
}

// В списке у всех ссылок один и тот же текст — «Информационное сообщение»,
// поэтому дату берём из самого адреса: он кончается на что-то вроде
// «o_provedenii_9_sentyabrya_2026_goda_auktsionov_po_razmeshcheniyu_ofz».
const МЕСЯЦЫ_ЛАТ = { yanvarya:1, fevralya:2, marta:3, aprelya:4, maya:5, iyunya:6,
                     iyulya:7, avgusta:8, sentyabrya:9, oktyabrya:10, noyabrya:11, dekabrya:12 };

function датаИзАдреса(url) {
  // В сообщениях о проведении адрес кончается на «_goda», в результатах — на
  // «_g». Поэтому окончание не требуем, а месяц проверяем по словарю.
  const m = /_(\d{1,2})_([a-z]+)_(\d{4})(?:_|$)/i.exec(String(url || ''));
  if (!m) return '';
  const мес = МЕСЯЦЫ_ЛАТ[m[2].toLowerCase()];
  if (!мес) return '';
  return m[3] + '-' + String(мес).padStart(2, '0') + '-' + String(+m[1]).padStart(2, '0');
}

// Из списка сообщений о проведении выбираем то, что относится к нужной дате
// аукциона. Отдельно помечаем сообщения о непроведении: в такие недели
// Минфин аукционы отменяет, и в календаре так и надо написать.
function найтиОбъявление(html, датаАукциона) {
  for (const с of ссылкиЛенты(html, 38)) {
    if (!/o_(ne)?provedenii/i.test(с.url)) continue;
    if (датаИзАдреса(с.url) !== датаАукциона) continue;
    return { url: с.url, отменён: /o_neprovedenii/i.test(с.url) };
  }
  return null;
}

// Результаты за день: у каждого выпуска своё сообщение, дата аукциона — в
// адресе. Возвращаем все, что нашлись на нужную дату.
function найтиРезультаты(html, датаАукциона) {
  const out = [];
  for (const с of ссылкиЛенты(html, 39)) {
    if (датаИзАдреса(с.url) !== датаАукциона) continue;
    out.push({ url: с.url });
  }
  return out;
}

// Из самого сообщения достаём номера выпусков и годы погашения.
// Строка в документе выглядит так: «выпуска № 26218RMFS (дата погашения
// 17 сентября 2031 года)». Выпусков бывает один, два, изредка три.
function разборОбъявления(html) {
  const т = текст(html);
  if (/о\s+непроведении/i.test(т)) return { отменён: true, выпуски: [], строка: 'аукционы не проводятся' };
  const выпуски = [];
  const re = /выпуска\s+№\s*(\d{5})([A-Z]{4})?\s*\(дата\s+погашения\s+([^)]{4,60}?)\)/gi;
  let m;
  while ((m = re.exec(т))) {
    const год = (/(\d{4})/.exec(m[3]) || [])[1] || '';
    if (выпуски.some(в => в.номер === m[1])) continue;
    выпуски.push({ номер: m[1], погашение: год });
  }
  // Короткая строка для календаря: «26218 (2031) и 26230 (2039)».
  const части = выпуски.map(в => в.погашение ? в.номер + ' (' + в.погашение + ')' : в.номер);
  const строка = части.length === 0 ? ''
    : части.length === 1 ? части[0]
    : части.slice(0, -1).join(', ') + ' и ' + части[части.length - 1];
  return { отменён: false, выпуски, строка };
}

module.exports = { РАЗДЕЛ, БАЗА, текст, датаИзТекста, датаИзАдреса, ссылкиЛенты,
                   найтиОбъявление, найтиРезультаты, разборОбъявления };
